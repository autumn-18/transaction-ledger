const v = require('./common');

/**
 * POST /api/accounts
 * Only "name" is accepted. id, balance and created_at are decided by the system.
 */
function validateCreateAccount(body) {
  v.assertBodyIsObject(body);
  const fieldErrors = [];

  v.checkUnknownFields(body, ['name'], fieldErrors, {
    balance: "'balance' cannot be set by the client. Every new account starts with a balance of 0; add money with a credit transaction.",
    id: "'id' is generated by the system and cannot be set",
    created_at: "'created_at' is generated by the system and cannot be set",
  });

  const name = v.requiredString(body.name, 'name', 255, fieldErrors);

  v.throwIfErrors(fieldErrors);
  return { name };
}

module.exports = { validateCreateAccount };
