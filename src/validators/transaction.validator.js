const config = require('../config');
const { ErrorCodes } = require('../utils/errors');
const v = require('./common');

/**
 * POST /api/accounts/:accountId/transactions
 * The account ID comes from the URL, so it is NOT accepted in the body.
 */
function validateCreateTransaction(body) {
  v.assertBodyIsObject(body);
  const fieldErrors = [];

  v.checkUnknownFields(body, ['type', 'amount', 'description', 'reference_id'], fieldErrors, {
    account_id: "'account_id' is taken from the URL (/api/accounts/:accountId/transactions) and must not be sent in the body",
    id: "'id' is generated by the system and cannot be set",
    created_at: "'created_at' is generated by the system and cannot be set",
  });

  const type = v.transactionType(body.type, 'type', fieldErrors);
  const amount = v.amount(body.amount, 'amount', fieldErrors);
  const description = v.optionalString(body.description, 'description', 500, fieldErrors);
  const referenceId = v.requiredString(body.reference_id, 'reference_id', 100, fieldErrors);

  v.throwIfErrors(fieldErrors);
  return { type, amount, description, referenceId };
}

/**
 * Parse a query parameter that must be a positive whole number.
 * Query values always arrive as strings ("2"), or as an array if the
 * parameter was repeated (?page=1&page=2), which we reject.
 */
function positiveInteger(raw, field, { defaultValue, max }, fieldErrors) {
  if (raw === undefined || raw === '') return defaultValue;
  if (typeof raw !== 'string' || !/^\d+$/.test(raw)) {
    fieldErrors.push({ field, code: ErrorCodes.INVALID_PAGINATION, message: `'${field}' must be a positive whole number` });
    return undefined;
  }
  const value = Number(raw);
  if (value < 1) {
    fieldErrors.push({ field, code: ErrorCodes.INVALID_PAGINATION, message: `'${field}' must be at least 1` });
    return undefined;
  }
  if (max !== undefined && value > max) {
    fieldErrors.push({ field, code: ErrorCodes.INVALID_PAGINATION, message: `'${field}' must not be greater than ${max}` });
    return undefined;
  }
  return value;
}

/**
 * GET /api/accounts/:accountId/transactions?type=&page=&limit=
 */
function validateHistoryQuery(query = {}) {
  const fieldErrors = [];
  const { defaultPage, defaultLimit, maxLimit } = config.pagination;

  // No type (or an empty ?type=) means "both credit and debit".
  let type = null;
  if (query.type !== undefined && query.type !== '') {
    type = v.transactionType(query.type, 'type', fieldErrors) ?? null;
  }

  // Number.MAX_SAFE_INTEGER guard: stops absurd values like page=99999999999999999999
  const page = positiveInteger(query.page, 'page', { defaultValue: defaultPage, max: Number.MAX_SAFE_INTEGER }, fieldErrors);
  const limit = positiveInteger(query.limit, 'limit', { defaultValue: defaultLimit, max: maxLimit }, fieldErrors);

  v.throwIfErrors(fieldErrors);
  return { type, page, limit };
}

module.exports = { validateCreateTransaction, validateHistoryQuery };
